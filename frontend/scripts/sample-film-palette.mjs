// =============================================================================
// FILM PALETTE SAMPLER
//
// Reads every chapter poster and derives the two colours the interface needs to
// dissolve into that film:
//
//   ground — the film's own darkness, taken from its darkest quartile. This
//            becomes the section background, so the film's edge meets a surface
//            of the same colour instead of a rectangle of a different black.
//   glow   — the film's brightest chromatic note, used for the section's
//            environmental light and its accent hairline.
//
// Grading an interface to its footage is the whole point: `--c-forest-900` is a
// green-black, and a charcoal grill film sitting on it reads as a patch. Sampled
// grounds make the boundary disappear.
//
// Writes src/app/features/home/sections/film-palette.ts. Re-run after any
// change to the posters.
//
// Usage: node scripts/sample-film-palette.mjs
// =============================================================================

import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const POSTERS = path.join(root, 'public', 'img', 'chapters');
const OUT = path.join(root, 'src', 'app', 'features', 'home', 'sections', 'film-palette.ts');

const hex = (r, g, b) =>
  '#' + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');

/** Perceived luminance, cheap and good enough for ranking pixels. */
const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

/** Distance from grey — how much colour a pixel actually carries. */
const chroma = (r, g, b) => Math.max(r, g, b) - Math.min(r, g, b);

/**
 * Lifts a colour toward a target luminance without changing its hue, so a
 * ground sampled from an almost-black frame still reads as that film's colour
 * rather than as pure black.
 */
function normalise([r, g, b], target) {
  const l = luma(r, g, b) || 1;
  const k = target / l;
  return [Math.min(255, r * k), Math.min(255, g * k), Math.min(255, b * k)];
}

async function sample(file) {
  // A tiny thumbnail is the sample: it averages local noise away and makes the
  // dominant fields of the frame the only thing left.
  const { data, info } = await sharp(file)
    .resize(48, 27, { fit: 'fill' })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const pixels = [];
  for (let i = 0; i < data.length; i += info.channels) {
    pixels.push([data[i], data[i + 1], data[i + 2]]);
  }

  const byLuma = [...pixels].sort((a, b) => luma(...a) - luma(...b));

  // GROUND: mean of the darkest quartile, then lifted to a consistent depth so
  // every chapter ground sits at the same weight in the page's rhythm.
  const darkest = byLuma.slice(0, Math.max(1, Math.floor(byLuma.length * 0.25)));
  const groundRaw = darkest
    .reduce((acc, p) => [acc[0] + p[0], acc[1] + p[1], acc[2] + p[2]], [0, 0, 0])
    .map((v) => v / darkest.length);
  const isHighKey = luma(...byLuma[Math.floor(byLuma.length / 2)]) > 150;
  const ground = normalise(groundRaw, isHighKey ? 236 : 22);

  // GLOW: the most chromatic pixel in the brighter half — the film's own
  // accent, the colour its light is actually made of.
  const brighter = byLuma.slice(Math.floor(byLuma.length * 0.5));
  const glowRaw = brighter.reduce((best, p) => (chroma(...p) > chroma(...best) ? p : best), brighter[0]);
  const glow = normalise(glowRaw, isHighKey ? 150 : 128);

  return { ground: hex(...ground), glow: hex(...glow), highKey: isHighKey };
}

const files = (await readdir(POSTERS)).filter((f) => f.endsWith('.jpg'));
const entries = [];

for (const file of files.sort()) {
  const slug = file.replace(/\.jpg$/, '');
  const { ground, glow, highKey } = await sample(path.join(POSTERS, file));
  entries.push({ slug, ground, glow, highKey });
  console.log(`${slug.padEnd(20)} ground ${ground}  glow ${glow}  ${highKey ? '(high key)' : ''}`);
}

const body = entries
  .map(
    (e) =>
      `  '${e.slug}': { ground: '${e.ground}', glow: '${e.glow}', highKey: ${e.highKey} },`,
  )
  .join('\n');

await writeFile(
  OUT,
  `// GENERATED by scripts/sample-film-palette.mjs — do not edit by hand.
//
// Each chapter's section is graded to its own film: \`ground\` is the film's
// darkness, so the media's edge meets a surface of the same colour and stops
// reading as a rectangle; \`glow\` is the colour that film's light is made of,
// used for its environmental bleed and accent hairline.

export interface FilmPalette {
  readonly ground: string;
  readonly glow: string;
  readonly highKey: boolean;
}

export const FILM_PALETTE: Readonly<Record<string, FilmPalette>> = {
${body}
};
`,
  'utf8',
);

console.log(`\nwrote ${path.relative(root, OUT)}`);
