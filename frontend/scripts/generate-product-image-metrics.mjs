import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';
import { supplierProducts } from './product-format-catalog.mjs';

const output = {};
for (const product of await supplierProducts()) {
  const src = product.images[0]?.src;
  if (!src || output[src]) continue;
  try {
    const { data, info } = await sharp(join('public', src))
      .resize({ width: 320, height: 320, fit: 'inside', withoutEnlargement: true })
      .flatten({ background: '#ffffff' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const corners = [0, info.width - 1, (info.height - 1) * info.width, info.height * info.width - 1];
    const whiteBackdrop = corners.every((pixel) =>
      data[pixel * 3] > 245 && data[pixel * 3 + 1] > 245 && data[pixel * 3 + 2] > 245);
    let minY = info.height, maxY = -1, minX = info.width, maxX = -1;
    for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
      const i = (y * info.width + x) * 3;
      const r = data[i], g = data[i + 1], b = data[i + 2];
      if (whiteBackdrop ? Math.min(r, g, b) < 242
        : Math.min(r, g, b) < 170 && (Math.max(r, g, b) - Math.min(r, g, b) > 25 || Math.max(r, g, b) < 115)) {
        minY = Math.min(minY, y); maxY = Math.max(maxY, y);
        minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      }
    }
    const occupancy = maxY >= minY ? (maxY - minY + 1) / info.height : 0;
    output[src] = {
      occupancy: +occupancy.toFixed(4),
      width: +(maxX >= minX ? (maxX - minX + 1) / info.width : 0).toFixed(4),
      bottom: +((maxY + 1) / info.height).toFixed(4),
      reliable: occupancy > 0.12 && minY > 1 && minX > 1 && maxX < info.width - 2 && maxY < info.height - 2,
    };
  } catch {
    output[src] = { occupancy: 0, width: 0, bottom: 0, reliable: false };
  }
}
// The API serves these measurements with each product image
// (backend ProductImageMetrics); the TypeScript copy is for the format audit
// script and the engine's unit tests only, never the storefront bundle.
await mkdir('../backend/src/main/resources/catalog', { recursive: true });
await writeFile('../backend/src/main/resources/catalog/product-image-metrics.json', `${JSON.stringify(output, null, 2)}
`);
await mkdir('src/app/data', { recursive: true });
await writeFile('src/app/data/product-image-metrics.generated.ts',
  `// Generated by scripts/generate-product-image-metrics.mjs from existing product photos.\n` +
  `// These are measured canvas bounds, not product-specific visual-size overrides.\n` +
  `export const PRODUCT_IMAGE_OCCUPANCY = ${JSON.stringify(output, null, 2)} as const;\n`);
console.log(`Measured ${Object.keys(output).length} catalogue images (${Object.values(output).filter((item) => item.reliable).length} reliable).`);
