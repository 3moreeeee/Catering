// Builds the dedicated MONIN catalogue from cached public category pages.
// Fetching is intentionally separate: save /49-monin?page=N as
// tmp/vinto-import/monin-page-N.html, then run this script. Add
// --download-images to refresh the local product photography.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseMeasures, toSlug } from './lib/normalize.mjs';
import { translateName } from './lib/lexicon.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const auditDir = path.join(root, 'tmp', 'vinto-import');
const imageDir = path.join(root, 'public', 'img', 'products', 'monin');
const target = path.join(root, 'src', 'app', 'data', 'products.monin.data.ts');
const downloadImages = process.argv.includes('--download-images');

const decode = (value) =>
  String(value ?? '')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(
      /&([a-z]+);/gi,
      (_, entity) =>
        ({ eacute: 'é', egrave: 'è', agrave: 'à', ccedil: 'ç', ocirc: 'ô' })[
          entity.toLowerCase()
        ] ?? `&${entity};`,
    );

const plain = (value) =>
  decode(value)
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
const quote = (value) => JSON.stringify(value);

const familyFor = (url, name) => {
  const segment = new URL(url).pathname.split('/').filter(Boolean)[0];
  if (segment === 'purees') return 'fruit-purees';
  if (segment === 'sauces') return 'sauces';
  if (segment === 'frappes') return 'frappe-bases';
  if (segment === 'accessoires-barista') return 'bar-tools';
  if (segment === 'sirops' || /sirop/i.test(name)) return 'syrups';
  return 'syrups';
};

const familyLabel = {
  syrups: { en: 'MONIN syrup', fr: 'sirop MONIN' },
  'fruit-purees': { en: 'MONIN fruit purée', fr: 'purée de fruits MONIN' },
  sauces: { en: 'MONIN gourmet sauce', fr: 'sauce gourmande MONIN' },
  'frappe-bases': { en: 'MONIN frappé base', fr: 'base frappé MONIN' },
  'bar-tools': { en: 'MONIN bar accessory', fr: 'accessoire de bar MONIN' },
};

const products = [];
for (let page = 1; page <= 5; page++) {
  const html = await readFile(path.join(auditDir, `monin-page-${page}.html`), 'utf8');
  const blocks = html.match(/<article class="[^"]*product-miniature[\s\S]*?<\/article>/g) ?? [];
  for (const block of blocks) {
    const id = block.match(/data-id-product="(\d+)"/)?.[1];
    const nameMatch = block.match(/class="product_name[^"]*"[^>]*title="([^"]+)"/);
    const urlMatch = block.match(
      /<a href="(https:\/\/vinto\.tn\/[^"#]+\/\d+-[^"#]+\.html)" class="thumbnail product-thumbnail"/,
    );
    const imageMatch = block.match(/data-full-size-image-url\s*=\s*"([^"]+)"/);
    if (!id || !nameMatch || !urlMatch || !imageMatch) continue;
    const name = plain(nameMatch[1]);
    const sourceUrl = decode(urlMatch[1]);
    const imageUrl = decode(imageMatch[1]);
    const sourceSlug = new URL(sourceUrl).pathname
      .split('/')
      .pop()
      .replace(/\.html$/, '');
    const slug = sourceSlug.replace(/^\d+-/, '');
    products.push({ id, name, sourceUrl, imageUrl, slug, family: familyFor(sourceUrl, name) });
  }
}

const unique = [...new Map(products.map((product) => [product.id, product])).values()];
if (unique.length !== 57) {
  throw new Error(`Expected 57 products from the five MONIN pages, found ${unique.length}`);
}

await mkdir(imageDir, { recursive: true });
if (downloadImages) {
  for (const [index, product] of unique.entries()) {
    const destination = path.join(imageDir, `${product.id}-${product.slug}.jpg`);
    const response = await fetch(product.imageUrl, {
      headers: { 'User-Agent': 'fk-catering-catalogue-sync/1.0 (+https://catering.com.tn)' },
    });
    if (!response.ok) throw new Error(`${response.status} while fetching ${product.imageUrl}`);
    await writeFile(destination, Buffer.from(await response.arrayBuffer()));
    process.stdout.write(`\rDownloaded ${index + 1}/${unique.length}`);
  }
  process.stdout.write('\n');
}

const records = unique.map((product, index) => {
  const translated = translateName(product.name).english || product.name;
  const measures = parseMeasures(product.name);
  const format = measures.map((measure) => `${measure.value} ${measure.unit}`).join(' · ');
  return `  [${[
    quote(product.id),
    quote(`monin-${toSlug(product.name)}-${product.id}`),
    quote(product.slug),
    quote(translated),
    quote(product.name),
    quote(product.family),
    quote(format),
    index < 8,
  ].join(', ')}]`;
});

const generated = `// GENERATED by scripts/sync-monin-vinto.mjs from https://vinto.tn/49-monin.
// Source snapshot: ${new Date().toISOString().slice(0, 10)}. Prices and stock are intentionally excluded.

import { Product } from '../shared/models/catalog.model';

const FAMILY = ${JSON.stringify(familyLabel, null, 2)} as const;

type MoninFamily = keyof typeof FAMILY;
type MoninSource = readonly [
  sourceId: string,
  slug: string,
  imageSlug: string,
  nameEn: string,
  nameFr: string,
  family: MoninFamily,
  format: string,
  featured: boolean,
];

const MONIN_SOURCE: readonly MoninSource[] = [
${records.join(',\n')},
];

export const MONIN_PRODUCTS: readonly Product[] = MONIN_SOURCE.map(
  ([sourceId, slug, imageSlug, nameEn, nameFr, family, format, featured]) => {
    const id = \`p-monin-\${sourceId}\`;
    const label = FAMILY[family];
    const formatEn = format ? \` Format: \${format}.\` : '';
    const formatFr = format ? \` Format : \${format}.\` : '';
    const labelFr = label.fr.charAt(0).toUpperCase() + label.fr.slice(1);

    return {
      id,
      slug,
      name: { en: nameEn, fr: nameFr },
      shortDescription: {
        en: \`\${label.en} for professional bars, cafés, hotels and restaurants.\${formatEn}\`,
        fr: \`\${labelFr} pour les bars, cafés, hôtels et restaurants professionnels.\${formatFr}\`,
      },
      description: {
        en: \`\${nameEn} is part of our dedicated MONIN range.\${formatEn} Availability, pack quantities and lead times are confirmed by our sales team on request.\`,
        fr: \`\${nameFr} fait partie de notre univers MONIN.\${formatFr} La disponibilité, les quantités par colis et les délais sont confirmés sur demande par notre équipe commerciale.\`,
      },
      categoryId: 'monin',
      subcategoryId: family,
      brandId: 'monin',
      industries: ['restaurants', 'hotels', 'retail'],
      formats: format ? [{ id: \`\${id}-f1\`, value: format }] : [],
      images: [{
        src: \`/img/products/monin/\${sourceId}-\${imageSlug}.v2.webp\`,
        alt: { en: \`\${nameEn} — product photograph\`, fr: \`\${nameFr} — photographie du produit\` },
        width: 800,
        height: 800,
      }],
      featured,
      seo: {
        title: { en: \`\${nameEn} | MONIN Tunisia\`, fr: \`\${nameFr} | MONIN Tunisie\` },
        description: {
          en: \`\${label.en} distributed in Tunisia by Société Ferid Khemakhem.\`,
          fr: \`\${labelFr} distribué en Tunisie par la Société Ferid Khemakhem.\`,
        },
      },
    } satisfies Product;
  },
);
`;

await writeFile(target, generated);
await writeFile(
  path.join(auditDir, 'monin-products.json'),
  JSON.stringify(
    {
      source: 'https://vinto.tn/49-monin',
      collectedAt: new Date().toISOString(),
      products: unique,
    },
    null,
    2,
  ),
);
console.log(`Generated ${unique.length} MONIN products in ${path.relative(root, target)}`);
